# transaction.py
import enum
import os
import uuid
from datetime import date as date_
from datetime import datetime, time, timedelta, timezone
from decimal import Decimal
from typing import Annotated, Optional
from zoneinfo import ZoneInfo

import boto3
import msgspec


# Every user has an undeletable account with this fixed id (see account.py);
# a transaction that doesn't name an account is assigned to it.
DEFAULT_ACCOUNT_ID = "default"

# Users are in Chile: a transaction's `date` is a Chilean calendar date, and
# one without a known time of day is placed at 00:00 Chilean time on it.
LOCAL_TIMEZONE = ZoneInfo("America/Santiago")


class TransactionType(str, enum.Enum):
    EXPENSE = "expense"
    INCOME = "income"
    TRANSFER = "transfer"  # moves money accountId -> targetAccountId; nets to zero overall


class StatementLine(msgspec.Struct):
    """One card purchase's installment billed on a statement (see statement.py)."""

    transactionId: str  # the purchase
    title: str
    date: date_  # purchase date
    installment: int  # which installment this is (1-based) ...
    installments: int  # ... out of how many
    amount: Decimal


class CardStatement(msgspec.Struct):
    """Breakdown carried by a card's monthly statement transaction. Server-managed."""

    accountId: str  # the credit card this statement bills
    installmentsDue: Decimal  # sum of `lines`
    previousBalance: Decimal  # still owed from the previous statement (negative = credit)
    amountDue: Decimal  # installmentsDue + previousBalance
    lines: list[StatementLine] = msgspec.field(default_factory=list)
    since: Optional[date_] = None  # first statement date of this card's chain (see statement.py); None on old items
    revision: int = 0  # bumped on every recalculation; guards concurrent recalculations


class Transaction(msgspec.Struct):
    # Required
    email: str  # matches User.email in api/auth/sync/models.py
    title: Annotated[str, msgspec.Meta(min_length=1)]
    amount: Decimal  # magnitude only; `type` gives direction (bounds checked in __post_init__)
    categories: list[str]
    date: date_
    type: TransactionType
    affectsBalance: bool
    pending: bool

    # Defaulted / optional
    # The exact moment, stored in UTC (sent with any offset, e.g. "...Z" or "...-03:00").
    # Falls back to 00:00 Chilean time on `date`; see __post_init__.
    full_date_utc: Optional[Annotated[datetime, msgspec.Meta(tz=True)]] = None
    transactionId: str = msgspec.field(default_factory=lambda: uuid.uuid4().hex)
    sk: str = ""  # DynamoDB sort key; computed in __post_init__ if not already set
    accountId: Optional[str] = None  # falls back to DEFAULT_ACCOUNT_ID; source account for a transfer
    targetAccountId: Optional[str] = None  # destination account; only set (and required) for transfers
    installments: Optional[Annotated[int, msgspec.Meta(ge=1)]] = None
    paymentDay: Optional[Annotated[int, msgspec.Meta(ge=1, le=31)]] = None
    # Optional link to one of the user's subscriptions: set on the bills the
    # daily job generates, or by the user on any transaction (see subscription.py)
    subscriptionId: Optional[str] = None
    billingPeriod: Optional[str] = None
    statement: Optional[CardStatement] = None  # set only on card statements generated by the statements job

    def __post_init__(self) -> None:
        # msgspec.Meta doesn't support numeric bounds on Decimal, so check here instead.
        # A pending transaction from a variable-amount subscription may not have
        # an amount yet (set later when the user pays it), so 0 is allowed only
        # while pending; a settled (non-pending) transaction must be > 0.
        if self.pending:
            if self.amount < 0:
                raise ValueError("amount must be >= 0 when pending is true")
        elif self.amount <= 0:
            raise ValueError("amount must be greater than 0")

        if not self.accountId:
            self.accountId = DEFAULT_ACCOUNT_ID
        if not self.subscriptionId:
            self.subscriptionId = None  # "" means no link, never a link to a subscription with an empty id

        # A transfer is a single movement between two of the user's accounts
        # (instead of an expense on one + an income on the other), so it needs
        # a destination; targetAccountId is meaningless on any other type.
        if self.type == TransactionType.TRANSFER:
            if not self.targetAccountId:
                raise ValueError("targetAccountId is required when type is transfer")
            if self.accountId == self.targetAccountId:
                raise ValueError("targetAccountId must be different from accountId")
        elif self.targetAccountId is not None:
            raise ValueError("targetAccountId is only allowed when type is transfer")

        if self.full_date_utc is None:
            self.full_date_utc = start_of_day_utc(self.date)
        else:
            self.full_date_utc = self.full_date_utc.astimezone(timezone.utc).replace(microsecond=0)
            # `date` is the user's local calendar date, so the moment must fall
            # on it in some timezone (UTC-12 to UTC+14). Catches a stale time
            # left over after the date was changed.
            day_start = datetime.combine(self.date, time(), tzinfo=timezone.utc)
            if not day_start - timedelta(hours=14) <= self.full_date_utc < day_start + timedelta(hours=36):
                raise ValueError("full_date_utc must fall on date")

        # Only derive sk on fresh creation; preserve it as-is when rehydrating
        # an item that already has one (e.g. read back from DynamoDB).
        if not self.sk:
            self.sk = build_sk(self.date, self.transactionId)


def start_of_day_utc(day: date_) -> datetime:
    """00:00 Chilean time on `day`, in UTC (03:00Z or 04:00Z depending on daylight saving time)."""
    return datetime.combine(day, time(), tzinfo=LOCAL_TIMEZONE).astimezone(timezone.utc)


def format_utc(moment: datetime) -> str:
    """How full_date_utc is stored and returned: "YYYY-MM-DDTHH:MM:SSZ"."""
    return moment.astimezone(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


# ---------- (De)serialization ----------
def decode_transaction(data: bytes | str) -> Transaction:
    """Decode + validate a Transaction from JSON bytes or string."""
    return msgspec.json.decode(data, type=Transaction)


def parse_transaction(data: dict) -> Transaction:
    """Validate + convert an already-parsed dict (e.g. an API Gateway body) into a Transaction."""
    return msgspec.convert(data, type=Transaction)


def encode_transaction(transaction: Transaction) -> bytes:
    """Encode a Transaction to JSON bytes."""
    return msgspec.json.encode(transaction)


# ---------- DynamoDB ----------
# Table key schema:
#   PK (partition key): email (String)  -> query all of a user's transactions in one Query
#   SK (sort key):      sk (String)     -> "<date ISO-8601>#<transactionId>"
#                                           date prefix keeps results sortable/queryable by
#                                           date range; transactionId suffix guarantees
#                                           uniqueness for same-day transactions.
def build_sk(date: date_ | str, transaction_id: str) -> str:
    """Build the table's sort key value from a date (date or ISO string) and transactionId."""
    iso_date = date if isinstance(date, str) else date.isoformat()
    return f"{iso_date}#{transaction_id}"


def get_transactions_table():
    """Return the DynamoDB Transactions table resource."""
    table_name = os.environ.get("TRANSACTIONS_TABLE")
    if not table_name:
        raise RuntimeError("TRANSACTIONS_TABLE environment variable is not set")

    dynamodb = boto3.resource("dynamodb")
    return dynamodb.Table(table_name)


def transaction_to_item(transaction: Transaction) -> dict:
    """Convert a Transaction into the plain dict stored in DynamoDB."""
    item = msgspec.structs.asdict(transaction)
    # DynamoDB has no native date/enum type; Decimal (amount) is already Dynamo-compatible.
    item["date"] = transaction.date.isoformat()
    item["full_date_utc"] = format_utc(transaction.full_date_utc)
    item["type"] = transaction.type.value
    if transaction.statement is not None:
        # asdict is shallow; turn the nested structs into plain maps (dates -> ISO strings)
        item["statement"] = msgspec.to_builtins(transaction.statement, builtin_types=(Decimal,))
    return item


def put_transaction(table, transaction: Transaction) -> None:
    """Write a transaction to DynamoDB WITHOUT touching account balances.

    Only for local seeding/tests. API handlers and the billing job must go
    through account.create_transaction / replace_transaction / delete_transaction
    so the Accounts table balances stay in sync.
    """
    table.put_item(Item=transaction_to_item(transaction))
